// Detects the guest's browser language and maps it to a supported one, defaulting to Italian
// (the property is Italian, so that's the safest fallback when the browser language isn't among the five).
export const detectLang = (): Lang => {
  const supported = LANGS.map(l => l.code);
  for (const nav of navigator.languages || [navigator.language]) {
    const base = nav.slice(0, 2).toLowerCase() as Lang;
    if (supported.includes(base)) return base;
  }
  return 'it';
};

