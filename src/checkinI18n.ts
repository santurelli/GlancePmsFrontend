export const t = (lang: Lang, key: Keys, vars?: Record<string, string | number>): string => {
  let str = TRANSLATIONS[lang][key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(`{${k}}`, String(v));
    }
  }
  return str;
};

// Maps our ISTAT citizenship codes to ISO 3166-1 alpha-2, so country names can be localized
// via Intl.DisplayNames instead of hand-translating ~20 names across 5 languages.
const ISTAT_TO_ISO2: Record<string, string> = {
  '100000100': 'IT', '100000012': 'DE', '100000021': 'FR', '100000046': 'ES',
  '100000027': 'GB', '100000201': 'US', '100000047': 'CH', '100000003': 'AT',
  '100000004': 'BE', '100000034': 'NL', '100000036': 'PL', '100000041': 'RO',
  '100000042': 'RU', '100000219': 'CN', '100000223': 'JP', '100000202': 'CA',
  '100000501': 'AU', '100000302': 'BR', '100000301': 'AR', '100000001': 'AL',
};

export const localizedCountryName = (istatCode: string, fallbackName: string, lang: Lang): string => {
  const iso2 = ISTAT_TO_ISO2[istatCode];
  if (!iso2) return fallbackName;
  try {
    return new Intl.DisplayNames([lang], { type: 'region' }).of(iso2) || fallbackName;
  } catch {
    return fallbackName;
  }
};
